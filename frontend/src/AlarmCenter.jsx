function translateAlarmMessage(
  value,
  language
) {
  if (!value) {
    return "--";
  }

  if (
    language !== "tr"
  ) {
    return value;
  }

  let translated =
    String(value);

  for (
    const [
      source,
      target,
    ] of ALARM_MESSAGE_REPLACEMENTS_TR
  ) {
    translated =
      translated.replaceAll(
        source,
        target
      );
  }

  return translated;
}


function formatDateTime(
  value,
  language
) {
  if (!value) {
    return "--";
  }

  return new Date(
    value
  ).toLocaleString(
    language === "tr"
      ? "tr-TR"
      : "en-GB",
    {
      day: "2-digit",
      month: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
    }
  );
}


function AlarmCenter({
  alarms = [],
  onOpenPanel,
  language = "tr",
}) {
  const safeLanguage =
    language === "en"
      ? "en"
      : "tr";

  const t =
    TEXT[safeLanguage];

  const [
    statusFilter,
    setStatusFilter,
  ] = useState("ALL");

  const [search, setSearch] =
    useState("");


  const openCount = useMemo(
    () =>
      alarms.filter(
        (alarm) =>
          alarm.status ===
          "OPEN"
      ).length,
    [alarms]
  );


  const resolvedCount =
    useMemo(
      () =>
        alarms.filter(
          (alarm) =>
            alarm.status ===
            "RESOLVED"
        ).length,
      [alarms]
    );


  const filteredAlarms =
    useMemo(() => {
      const searchValue =
        search
          .trim()
          .toLowerCase();

      return [...alarms]
        .filter((alarm) => {
          const matchesStatus =
            statusFilter ===
              "ALL" ||
            alarm.status ===
              statusFilter;

          const matchesSearch =
            !searchValue ||
            alarm.panel_id
              ?.toLowerCase()
              .includes(
                searchValue
              ) ||
            alarm.primary_risk
              ?.toLowerCase()
              .includes(
                searchValue
              ) ||
            alarm.message
              ?.toLowerCase()
              .includes(
                searchValue
              );

          return (
            matchesStatus &&
            matchesSearch
          );
        })
        .sort((a, b) => {
          const aTime =
            new Date(
              a.opened_at ??
              0
            ).getTime();

          const bTime =
            new Date(
              b.opened_at ??
              0
            ).getTime();

          return (
            bTime - aTime
          );
        });
    }, [
      alarms,
      statusFilter,
      search,
    ]);


  return (
    <section className="alarm-center">

      <div className="alarm-center-heading">

        <div>
          <p className="eyebrow">
            {t.eyebrow}
          </p>

          <h3>
            {t.title}
          </h3>

          <p>
            {t.subtitle}
          </p>
        </div>


        <div className="alarm-summary-strip">

          <div className="alarm-summary-item">
            <span>
              {t.open}
            </span>

            <strong className="alarm-open-number">
              {openCount}
            </strong>
          </div>


          <div className="alarm-summary-item">
            <span>
              {t.resolved}
            </span>

            <strong className="alarm-resolved-number">
              {resolvedCount}
            </strong>
          </div>


          <div className="alarm-summary-item">
            <span>
              {t.total}
            </span>

            <strong>
              {alarms.length}
            </strong>
          </div>

        </div>

      </div>


      <div className="alarm-controls">

        <input
          type="text"
          placeholder={
            t.search
          }
          value={search}
          onChange={(event) =>
            setSearch(
              event.target.value
            )
          }
        />


        <div className="alarm-filter-tabs">

          {[
            ["ALL", t.all],
            ["OPEN", t.open],
            [
              "RESOLVED",
              t.resolved,
            ],
          ].map(
            ([
              key,
              label,
            ]) => (
              <button
                type="button"
                className={
                  statusFilter ===
                  key
                    ? "active"
                    : ""
                }
                onClick={() =>
                  setStatusFilter(
                    key
                  )
                }
                key={key}
              >
                {label}
              </button>
            )
          )}

        </div>

      </div>


      <div className="alarm-table-wrapper">

        <table className="alarm-table">

          <thead>
            <tr>
              <th>
                {t.status}
              </th>
              <th>
                {t.panel}
              </th>
              <th>
                {t.severity}
              </th>
              <th>
                {t.risk}
              </th>
              <th>
                {t.primaryRisk}
              </th>
              <th>
                {t.message}
              </th>
              <th>
                {t.opened}
              </th>
              <th>
                {t.resolvedAt}
              </th>
            </tr>
          </thead>


          <tbody>

            {filteredAlarms.length ===
            0 ? (

              <tr>
                <td
                  colSpan="8"
                  className="alarm-empty-cell"
                >
                  {t.empty}
                </td>
              </tr>

            ) : (

              filteredAlarms.map(
                (alarm) => (

                  <tr
                    key={alarm.id}
                    className={
                      alarm.status ===
                      "OPEN"
                        ? "open-alarm-row"
                        : ""
                    }
                  >

                    <td>
                      <span
                        className={`alarm-status-badge ${
                          (
                            alarm.status ??
                            "unknown"
                          ).toLowerCase()
                        }`}
                      >
                        {mapLabel(
                          STATUS,
                          safeLanguage,
                          alarm.status
                        )}
                      </span>
                    </td>


                    <td>
                      <button
                        type="button"
                        className="alarm-panel-button"
                        onClick={() =>
                          onOpenPanel(
                            alarm.panel_id
                          )
                        }
                      >
                        {
                          alarm.panel_id
                        }
                      </button>
                    </td>


                    <td>
                      <span
                        className={`alarm-severity-badge ${
                          (
                            alarm.severity ??
                            "unknown"
                          ).toLowerCase()
                        }`}
                      >
                        {mapLabel(
                          SEVERITY,
                          safeLanguage,
                          alarm.severity
                        )}
                      </span>
                    </td>


                    <td className="alarm-risk-score">
                      {
                        alarm.risk_score ??
                        0
                      }
                    </td>


                    <td>
                      {mapLabel(
                        PRIMARY_RISK,
                        safeLanguage,
                        alarm.primary_risk
                      )}
                    </td>


                    <td className="alarm-message-cell">
                      {translateAlarmMessage(
                        alarm.message,
                        safeLanguage
                      )}
                    </td>


                    <td>
                      {formatDateTime(
                        alarm.opened_at,
                        safeLanguage
                      )}
                    </td>


                    <td>
                      {alarm.status ===
                      "RESOLVED"
                        ? formatDateTime(
                            alarm.resolved_at,
                            safeLanguage
                          )
                        : "--"}
                    </td>

                  </tr>

                )
              )

            )}

          </tbody>

        </table>

      </div>


      <div className="alarm-center-footer">
        {t.showing}

        <strong>
          {
            filteredAlarms.length
          }
        </strong>

        {t.of}

        <strong>
          {alarms.length}
        </strong>

        {t.records}
      </div>

    </section>
  );
}


export default AlarmCenter;
